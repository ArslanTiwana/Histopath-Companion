import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import ts from "typescript";

const root = new URL("..", import.meta.url);
const catalog = JSON.parse(
  await readFile(
    new URL("../lib/action-catalog.json", import.meta.url),
    "utf8",
  ),
);
const discovered = [];

async function scan(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const filename = path.join(directory, entry.name);
    if (entry.isDirectory()) await scan(filename);
    else if (/\.tsx?$/.test(entry.name)) {
      const source = await readFile(filename, "utf8");
      const file = ts.createSourceFile(
        filename,
        source,
        ts.ScriptTarget.Latest,
        true,
        ts.ScriptKind.TSX,
      );
      const visit = (node) => {
        if (
          ts.isCallExpression(node) &&
          node.expression.getText(file) === "defineAction" &&
          ts.isObjectLiteralExpression(node.arguments[0])
        ) {
          const values = Object.fromEntries(
            node.arguments[0].properties
              .filter(ts.isPropertyAssignment)
              .map((property) => [
                property.name.getText(file),
                property.initializer,
              ]),
          );
          if (
            values.id &&
            ts.isStringLiteral(values.id) &&
            values.description &&
            ts.isStringLiteral(values.description) &&
            values.risk &&
            ts.isStringLiteral(values.risk) &&
            values.screens &&
            ts.isArrayLiteralExpression(values.screens)
          ) {
            const screen = values.screens.elements.find(
              ts.isStringLiteral,
            )?.text;
            if (screen)
              discovered.push({
                screen,
                id: values.id.text,
                risk: values.risk.text,
                description: values.description.text,
              });
          }
        }
        ts.forEachChild(node, visit);
      };
      visit(file);
    }
  }
}
await scan(new URL("../app", import.meta.url).pathname);

const merged = new Map();
for (const action of [...catalog, ...discovered])
  merged.set(`${action.screen}:${action.id}`, action);
const grouped = new Map();
for (const action of merged.values()) {
  const actions = grouped.get(action.screen) || [];
  actions.push(action);
  grouped.set(action.screen, actions);
}
const lines = [
  "# Voice action registry",
  "",
  "Generated by `npm run actions:list`. Risky actions use the persisted confirmation-token flow.",
  "",
];
for (const [screen, actions] of grouped) {
  lines.push(
    `## ${screen}`,
    "",
    "| Action | Risk | Description |",
    "|---|---|---|",
  );
  for (const action of actions.sort((a, b) => a.id.localeCompare(b.id)))
    lines.push(`| \`${action.id}\` | ${action.risk} | ${action.description} |`);
  lines.push("");
}
await writeFile(
  new URL("../docs/voice-actions.md", import.meta.url),
  `${lines.join("\n")}\n`,
);
